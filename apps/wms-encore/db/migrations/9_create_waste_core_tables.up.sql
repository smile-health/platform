CREATE TABLE waste_hierarchy (
    id SERIAL PRIMARY KEY,
    created_by TEXT NOT NULL,
    updated_by TEXT NOT NULL,
    region_id INTEGER NOT NULL REFERENCES regions (id),
    parent_hierarchy_id INTEGER REFERENCES waste_hierarchy (id),
    name TEXT NOT NULL,
    name_en TEXT NOT NULL,
    description TEXT,
    description_en TEXT,
    level INTEGER NOT NULL DEFAULT 0,
    is_residue BOOLEAN DEFAULT false,
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ,
    deleted_by INTEGER
);

CREATE TYPE waste_bag_color_code AS ENUM ('BLACK', 'GRAY', 'YELLOW', 'PURPLE', 'BROWN', 'RED', 'NONE');
CREATE TYPE storage_rule_type AS ENUM ('STATIC', 'RULE_BASED');

CREATE TABLE waste_classification (
    id SERIAL PRIMARY KEY,
    created_by TEXT NOT NULL,
    updated_by TEXT NOT NULL,
    region_id INTEGER NOT NULL REFERENCES regions (id),
    effective_from TIMESTAMPTZ NOT NULL,
    effective_to TIMESTAMPTZ NOT NULL,
    waste_type_id INTEGER NOT NULL REFERENCES waste_hierarchy (id),
    waste_group_id INTEGER NOT NULL REFERENCES waste_hierarchy (id),
    waste_characteristics_id INTEGER NOT NULL REFERENCES waste_hierarchy (id),
    waste_code TEXT NOT NULL,
    waste_bag_color_code waste_bag_color_code NOT NULL,
    storage_rule_type storage_rule_type,
    use_cold_storage BOOLEAN NOT NULL DEFAULT false,
    cold_storage_min_hours INTEGER,
    cold_storage_max_hours INTEGER,
    temp_storage_min_hours INTEGER,
    temp_storage_max_hours INTEGER,
    minimun_decay_day INTEGER,
    storage_rule JSONB,
    allow_healthcare_facility_treatment BOOLEAN NOT NULL DEFAULT true,
    is_active BOOLEAN NOT NULL DEFAULT true,
    has_multiple_transporters BOOLEAN NOT NULL DEFAULT false,
    treatment_method TEXT,
    disposal_method TEXT,
    allowed_vehicle_types TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ,
    deleted_by INTEGER
);

CREATE TYPE waste_source_type AS ENUM ('INTERNAL', 'EXTERNAL', 'INTERNAL_TREATMENT');
CREATE TYPE internal_treatment_name AS ENUM ('PYROLYSIS', 'DISINFECTION');

CREATE TABLE waste_source (
    id SERIAL PRIMARY KEY,
    created_by TEXT NOT NULL,
    updated_by TEXT NOT NULL,
    healthcare_facility_id INTEGER NOT NULL,
    source_type waste_source_type NOT NULL DEFAULT 'INTERNAL',
    internal_source_name TEXT,
    internal_treatment_name internal_treatment_name,
    external_healthcare_facility_id INTEGER,
    external_healthcare_facility_name TEXT,
    is_active BOOLEAN NOT NULL DEFAULT true,
    is_residue BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ,
    deleted_by INTEGER
);

