    asset_id INTEGER,
    weight_in_kgs NUMERIC(10, 2),
    storage_start_timestamp TIMESTAMPTZ,
    scheduled_storage_end_datetime TIMESTAMPTZ,
    actual_storage_end_timestamp TIMESTAMPTZ,
    max_storage_hours INTEGER,
    min_storage_hours INTEGER,
    waste_treatment_group_id INTEGER,
    waste_transportation_group_id INTEGER,
    waste_treatment_external_group_id INTEGER,
    waste_transportation_external_group_id INTEGER,
    waste_status TEXT NOT NULL DEFAULT 'IN_TEMPORARY_STORAGE',
    waste_status_updated_at TIMESTAMPTZ DEFAULT now(),
    waste_status_updated_by TEXT,
    transportation_status TEXT,
    transportation_status_updated_at TIMESTAMPTZ DEFAULT now(),
    transportation_status_updated_by TEXT,
    owned_by TEXT NOT NULL DEFAULT 'HEALTHCARE_FACILITY',
    transporter_id INTEGER,
    third_party_id INTEGER,
    is_treated BOOLEAN NOT NULL DEFAULT false,
    is_disposed BOOLEAN NOT NULL DEFAULT false,
    bin_number TEXT,
    iot_method TEXT,
    manifest_doc_number TEXT,
    manifest_doc_path TEXT,
    treatment_start_time TIMESTAMPTZ,
    treatment_end_time TIMESTAMPTZ,
    waste_group_ids TEXT,
    treatment_location_id INTEGER,
    healthcare_facility_name TEXT,
    province_id INTEGER,
    province_name TEXT,
    regency_id INTEGER,
    regency_name TEXT,
    district_id INTEGER,
    district_name TEXT,
    transporter_name TEXT,
    third_party_name TEXT,
    bast_no TEXT,
    material_ids TEXT,
    deleted_at TIMESTAMPTZ,
